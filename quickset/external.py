def corpus_dir(corpus: ExternalCorpus) -> Path:
    return CACHE_DIR / corpus.id


def is_fetched(corpus: ExternalCorpus) -> bool:
    d = corpus_dir(corpus)
    return d.is_dir() and any(d.iterdir())


def fetch(corpus: ExternalCorpus) -> int:
    """Download and extract one corpus. Returns the file count."""
    dest = corpus_dir(corpus)
    if is_fetched(corpus):
        return len(list(dest.iterdir()))

    dest.mkdir(parents=True, exist_ok=True)
    with urllib.request.urlopen(corpus.url) as response:  # noqa: S310 - pinned HTTPS
        blob = response.read()

    count = 0
    with tarfile.open(fileobj=io.BytesIO(blob), mode="r:gz") as tar:
        for member in tar.getmembers():
            if not member.isfile():
                continue
            # Archive paths start with a repo-name/commit prefix, so match on
            # the suffix rather than the whole path.
            if corpus.member_prefix not in member.name:
                continue
            # Flatten into one directory and take only the basename, which
            # also neutralises any path-traversal entry in the archive.
            name = Path(member.name).name
            if not name or name.startswith("."):
                continue
            extracted = tar.extractfile(member)
            if extracted is None:
                continue
            (dest / name).write_bytes(extracted.read())
            count += 1
    return count


def label_of(corpus: ExternalCorpus, filename: str) -> bool | None:
    """True if malicious, False if benign, None if the author does not say.

    Never guesses. A file the corpus does not label is excluded from scoring.
    """
    if filename in corpus.unlabelled:
        return None
    if corpus.all_malicious:
        return True
    if filename in corpus.asserted_malicious:
        return True
    if filename.startswith("malicious"):
        return True
    if filename.startswith("benign"):
        return False
    return None


def fetch_all() -> int:
    ok = True
    for corpus in CORPORA:
        try:
            n = fetch(corpus)
            print(f"  {corpus.id}: {n} files  [{corpus.license}]")
        except Exception as exc:
            print(f"  {corpus.id}: FAILED ({exc})")
            ok = False
    if ok:
        print()
        print("These are real exploits. They are gitignored and are never")
        print("loaded or unpickled, only scanned as bytes.")
    return 0 if ok else 1


def purge() -> None:
    """Delete the cache. Worth having, since it holds working exploits."""
    if CACHE_DIR.exists():
        shutil.rmtree(CACHE_DIR)
        print(f"removed {CACHE_DIR}")


if __name__ == "__main__":
    import sys

    if "--purge" in sys.argv:
        purge()
        raise SystemExit(0)
    raise SystemExit(fetch_all())
