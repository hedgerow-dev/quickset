"""Externally-authored corpora, fetched rather than vendored.

This project's own corpus was written here, so its numbers flatter whatever it
was written alongside. That is stated in the README, but stating a bias does
not remove it. The corpora below were authored by other people, and every one
of them has found a real bug that this project's own cases did not.

They are fetched to a gitignored cache and never committed, for the same
reason the generated payloads are never committed: these are working exploits,
not inert markers like the ones in `cases.py`. Nothing here loads or unpickles
them. They are scanned as bytes.

Ground truth is taken from each corpus's own labelling and never guessed. Where
a file's label is not stated by its author, it is excluded from scoring rather
than assigned one, because inventing labels is how a benchmark quietly becomes
a measurement of its own assumptions.
"""

from __future__ import annotations

import io
import shutil
import tarfile
import urllib.request
from dataclasses import dataclass
from pathlib import Path

CACHE_DIR = Path(__file__).resolve().parent.parent / "external-cache"


@dataclass(frozen=True)
class ExternalCorpus:
    """One externally-authored corpus."""

    id: str
    name: str
    # Pinned to a commit, never to a branch head. These corpora are upstream
    # repositories that keep moving, so `refs/heads/main` meant every number
    # published against them was measured on a snapshot nobody could name and
    # nobody could get back. That is the same failure the benign manifest pins
    # SHA-256 to avoid, and it had no business being treated differently just
    # because the source is a git host.
    url: str
    commit: str
    # Archive members under this path are the corpus.
    member_prefix: str
    license: str
    origin: str
    note: str = ""
    # Files whose label the corpus author does not state. Scored as neither.
    unlabelled: frozenset[str] = frozenset()
    # Files the author's tests assert malicious despite a name outside the
    # malicious* convention. Evidence over convention.
    asserted_malicious: frozenset[str] = frozenset()
    # When set, every file in the corpus is malicious by construction.
    all_malicious: bool = False


